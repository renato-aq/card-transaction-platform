using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace CardPlatform.Messaging.Outbox;

/// <summary>
/// EF Core mapping of <see cref="OutboxMessage"/> to <c>outbox_messages</c>, applied by
/// <see cref="OutboxModelBuilderExtensions.ApplyOutbox"/>. Written for PostgreSQL with the snake_case naming convention
/// that every service context uses (the filter of the unpublished index names <c>published_at</c>).
/// </summary>
public sealed class OutboxMessageConfiguration : IEntityTypeConfiguration<OutboxMessage>
{
    public const string TableName = "outbox_messages";

    public const string PrimaryKeyName = "pk_outbox_messages";

    /// <summary>
    /// Partial index of the rows still to publish, in the order they were written: what the publisher reads.
    /// </summary>
    public const string UnpublishedIndexName = "ix_outbox_messages_unpublished";

    public const int TypeMaxLength = 100;

    public const int PartitionKeyMaxLength = 100;

    /// <summary>Kafka's limit on topic names.</summary>
    public const int TopicMaxLength = 249;

    public void Configure(EntityTypeBuilder<OutboxMessage> builder)
    {
        ArgumentNullException.ThrowIfNull(builder);

        builder.ToTable(TableName);

        // The row id is generated by the database (identity); the event id is not unique (see OutboxMessage).
        builder.HasKey(message => message.Id).HasName(PrimaryKeyName);
        builder.Property(message => message.Id).ValueGeneratedOnAdd();

        builder.Property(message => message.Type).HasMaxLength(TypeMaxLength);
        builder.Property(message => message.PartitionKey).HasMaxLength(PartitionKeyMaxLength);
        builder.Property(message => message.Topic).HasMaxLength(TopicMaxLength);

        // jsonb: PostgreSQL checks it is JSON and it can be queried; the envelope does not depend on key order.
        builder.Property(message => message.Payload).HasColumnType("jsonb");

        // CreatedAt and PublishedAt are timestamptz; Npgsql only writes UTC offsets, so OutboxMessage stores them in UTC.

        builder.HasIndex(message => new { message.CreatedAt, message.Id })
            .HasDatabaseName(UnpublishedIndexName)
            .HasFilter("published_at IS NULL");
    }
}
